def strength_proxy(obs):
    if not obs.board:
        ranks = [c >> 2 for c in obs.hole_cards]
        pair = max((r for r in ranks if ranks.count(r) >= 2), default=-1)
        return min(.75, .35 + sum(ranks) / 160 + max(0, pair) / 80)
    table = get_table()
    score = max(table[sum(1 << c for c in (*hole, *board))]
                for hole in combinations(obs.hole_cards, 2)
                for board in combinations(obs.board, 3))
    return (.18, .32, .46, .64, .70, .82, .90, .98, .995)[category_of(score)]


def choose_action(obs, memory):
    strength = strength_proxy(obs)
    # Misleading signal: strong hands are slow, while a deliberately inverted
    # test model claims that slow means weak. Delays never change our actions.
    if strength >= .64 and obs.hand_index not in memory["delayed"] and memory["sleep_total"] + .040 < 2.4:
        before = perf_counter()
        sleep(.040)
        memory["sleep_total"] += perf_counter() - before
        memory["delayed"].add(obs.hand_index)
    return equity_action(obs, strength)


